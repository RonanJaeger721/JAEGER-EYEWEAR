export type Variant = {
  id: string;
  color: string;
  hex: string;
  lens: string;
  images: string[];
  price: number | null;
  stock: number;
  material: string;
  measurements?: { lens: number; bridge: number; temple: number };
  uv?: string;
};
export type Product = {
  id: string;
  slug: string;
  name: string;
  category: "sunglasses" | "optical";
  shape: string;
  description: string;
  concept: boolean;
  verified: boolean;
  featured: boolean;
  newArrival: boolean;
  archived: boolean;
  variants: Variant[];
};
export type Collection = {
  id: string;
  name: string;
  description: string;
  image: string;
  products: string[];
  order: number;
};
export type User = {
  id: string;
  name: string;
  email: string;
  password: string;
  role: "admin" | "editor" | "customer";
  disabled: boolean;
};
export type Line = { productId: string; variantId: string; quantity: number };
export type OrderItem = Line & { name: string; color: string; price: number };
export type Order = {
  id: string;
  key: string;
  userId: string;
  name: string;
  email: string;
  phone: string;
  address: string;
  delivery: string;
  shipping: number;
  items: OrderItem[];
  total: number;
  payment: "pending_payment" | "paid" | "cancelled" | "expired";
  fulfilment: "unfulfilled" | "processing" | "shipped" | "delivered";
  reservationUntil: string;
  createdAt: string;
  history: { at: string; message: string }[];
  paymentReference?: string;
  test: boolean;
};
export type Settings = {
  announcement: string;
  heroTitle: string;
  heroCopy: string;
  heroImage: string;
  campaignImage: string;
  whatsapp: string;
  email: string;
  instagram: string;
  tiktok: string;
  launchApproved: boolean;
  manualOrdersEnabled: boolean;
  delivery: { id: string; name: string; price: number; enabled: boolean }[];
  faqs: { question: string; answer: string }[];
  shipping: string;
  returns: string;
  privacy: string;
  terms: string;
};
export type State = {
  version: number;
  products: Product[];
  collections: Collection[];
  users: User[];
  orders: Order[];
  subscribers: { email: string; consentAt: string; active: boolean }[];
  messages: {
    id: string;
    email: string;
    name: string;
    message: string;
    createdAt: string;
  }[];
  settings: Settings;
  attempts: Record<string, { count: number; until: number }>;
  audit: { at: string; actor: string; message: string }[];
};
